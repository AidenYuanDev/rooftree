-- arena's tables. Applied by the server at every start (Database.Arena), so every statement must be
-- safe to run again. When a table changes here, add an idempotent ALTER below instead of editing the
-- CREATE of a database already in use.

CREATE TABLE IF NOT EXISTS account (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      varchar(16)  NOT NULL UNIQUE,
  password_hash varchar(128) NOT NULL,                  -- Argon2id, encoded with its parameters and salt
  created_at    timestamptz  NOT NULL DEFAULT now(),
  last_login    timestamptz
);

CREATE TABLE IF NOT EXISTS player (
  account_id  bigint PRIMARY KEY REFERENCES account (id) ON DELETE CASCADE,
  total_coins bigint NOT NULL DEFAULT 0,
  play_time   bigint NOT NULL DEFAULT 0                 -- seconds
);

CREATE INDEX IF NOT EXISTS player_total_coins ON player (total_coins);
