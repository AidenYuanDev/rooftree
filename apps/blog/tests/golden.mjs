// Times, tokens and machine numbers change from run to run
function normalize(value, key = '') {
  if (Array.isArray(value))
    return value.map((item) => normalize(item, key))
  if (value && typeof value === 'object')
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [/^[\w-]{22}\.\w+$/.test(k) ? '<upload>' : k, normalize(v, k)]))
  if (typeof value === 'string' && /^\d{4}-\d\d-\d\dT[\d:.]+Z$/.test(value))
    return '<time>'
  if (typeof value === 'string' && /^\d{4}-\d\d-\d\d$/.test(value))
    return '<day>'
  if (typeof value === 'string' && /^\/uploads\//.test(value))
    return '<upload>'
  if (typeof value === 'string' && key === 'nextCursor')
    return '<cursor>'
  if (typeof value === 'string' && ['secret', 'otpauthUri', 'csrfToken', 'token'].includes(key))
    return '<secret>'
  if (typeof value === 'string' && /^[0-9a-fA-F]{64}$/.test(value))
    return '<hash>'
  if (typeof value === 'string' && key === 'id' && /^[\w-]{32}$/.test(value))
    return '<upload id>'
  if (typeof value === 'number' && ['free', 'total', 'uptime', 'at', 'requests', 'updateAvgUs', 'updateMaxUs', 'memoryMiB', 'cpuPercent',
    'load', 'hostMemoryPercent', 'diskFreePercent', 'cores', 'readers', 'pages', 'onlineSeconds', 'viewers', 'users', 'minFree'].includes(key))
    return '<number>'
  return value
}

// The headers an answer's JSON doesn't show
const headers = ['location', 'retry-after', 'cache-control']

async function record(label, call) {
  const response = await call
  const shown = Object.fromEntries(headers.filter((name) => response.headers.has(name)).map((name) => [name, response.headers.get(name)]))
  records.push({ label, status: response.status, json: normalize(response.json), ...(Object.keys(shown).length ? { headers: shown } : {}) })
  return response.json
}

