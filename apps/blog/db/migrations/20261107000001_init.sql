CREATE TABLE post (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug varchar(100) NOT NULL UNIQUE,                 -- lower case letters, digits and -
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  original_lang text NOT NULL CHECK (original_lang IN ('zh', 'en')),
  cover varchar(255) NOT NULL DEFAULT '',
  author_id bigint NOT NULL REFERENCES users (id),
  comments_enabled boolean NOT NULL DEFAULT true,
  word_count bigint NOT NULL DEFAULT 0,              -- of the original language, for the home page
  created_at timestamp(0) NOT NULL DEFAULT utc_now(),
  updated_at timestamp(0) NOT NULL DEFAULT utc_now(),
  published_at timestamp(0),                         -- first publication, kept when unpublished again
  publish_at timestamp(0),
  mailed_at timestamp(0),
  review_requested_at timestamp(0),
  review_requested_by bigint
);
CREATE INDEX post_published ON post (status, published_at, id);
CREATE INDEX post_author ON post (author_id);
CREATE INDEX post_publish_at ON post (publish_at);

