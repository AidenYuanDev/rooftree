CREATE TABLE comment (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id bigint REFERENCES post (id) ON DELETE CASCADE,
  note_id bigint REFERENCES note (id) ON DELETE CASCADE,
  thinking_id bigint REFERENCES thinking (id) ON DELETE CASCADE,
  target_kind text NOT NULL DEFAULT 'post' CHECK (target_kind IN ('post', 'note', 'thinking', 'guestbook')),
  target_id bigint NOT NULL DEFAULT 0,               -- 0 for the guestbook
  user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  parent_id bigint REFERENCES comment (id) ON DELETE CASCADE,  -- the top-level comment of the thread, NULL for one
  reply_to_user_id bigint,                           -- the "@user" of a reply
  reply_to_id bigint,                                -- the comment answered, a reply's
  body text NOT NULL,
  status text NOT NULL DEFAULT 'visible' CHECK (status IN ('visible', 'hidden', 'deleted')),
  created_at timestamp(0) NOT NULL DEFAULT utc_now(),
  edited_at timestamp(0),
  ip varchar(45) NOT NULL,
  anchor_lang text CHECK (anchor_lang IN ('zh', 'en')),  -- the passage's: the language version of the post
  anchor_block bigint,                               -- its block's number in the post, a hint only
  anchor_quote varchar(300),                         -- the selected text
  anchor_prefix varchar(32),                         -- the text right before it in its block
  anchor_suffix varchar(32),                         -- the text right after it
  anchor_text text,                                  -- its whole block as it was, shown once the post changed
  anchor_revision bigint,                            -- the post_revision it was made on
  anchor_status text NOT NULL DEFAULT 'ok' CHECK (anchor_status IN ('ok', 'orphaned', 'kept'))  -- orphaned: its text is no longer in the post; kept: the admin left it so
);
CREATE INDEX comment_parent ON comment (parent_id);
