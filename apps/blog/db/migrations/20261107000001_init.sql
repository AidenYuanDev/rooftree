-- Names compare by their bytes (COLLATE "C"): two names differing in case are two files
CREATE TABLE drive_folder (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  parent_id bigint REFERENCES drive_folder (id) ON DELETE CASCADE,
  parent_key bigint GENERATED ALWAYS AS (COALESCE(parent_id, 0)) STORED,
  name varchar(255) COLLATE "C" NOT NULL,
  created_at timestamp(0) NOT NULL DEFAULT utc_now(),
  trashed_at timestamp(0),
  trash_key bigint NOT NULL DEFAULT 0,
  UNIQUE (user_id, parent_key, name, trash_key)
);
CREATE INDEX drive_folder_parent ON drive_folder (parent_id);
CREATE INDEX drive_folder_trashed ON drive_folder (trashed_at);

CREATE TABLE drive_file (
