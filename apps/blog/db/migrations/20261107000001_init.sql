-- MySQL's utf8mb4_0900_ai_ci let "Bob" and "bob" be one name: unique and equal ignoring case
CREATE COLLATION ci (provider = icu, locale = 'und-u-ks-level2', deterministic = false);

-- Now in UTC, in whole seconds as every timestamp here is
CREATE FUNCTION utc_now() RETURNS timestamp(0) LANGUAGE sql STABLE AS $$ SELECT date_trunc('second', now() AT TIME ZONE 'utc')::timestamp(0) $$;

CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(20) COLLATE ci NOT NULL UNIQUE,   -- letters, digits, _
  display_name varchar(40) NOT NULL,
  avatar varchar(64),                                -- avatar-<token>.<webp|png|jpg> in Blog.Uploads.Directory
  email varchar(254) COLLATE ci NOT NULL UNIQUE,
  email_verified_at timestamp(0),
  password_hash varchar(255),                        -- Argon2id, encoded with its parameters and salt; NULL: logs in with GitHub or Google only
  role text NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'moderator', 'user')),
  denied text NOT NULL DEFAULT '',                   -- comma separated: comment, react, avatar, friend, chat
  granted text NOT NULL DEFAULT '',                  -- comma separated: drive, write
  drive_quota bigint,
  drive_trash_days integer,
  locale text NOT NULL DEFAULT 'zh' CHECK (locale IN ('zh', 'en')),
  reply_mails boolean NOT NULL DEFAULT false,
  totp_secret bytea,                                 -- set once two-step login is on
  totp_pending_secret bytea,                         -- between setup and the first code
  totp_last_step bigint,                             -- time step of the last accepted code, against replays
  banned_until timestamp(0),                         -- NULL: not banned; 2200-01-01: for good
  ban_reason varchar(255),
  deleted_at timestamp(0),                           -- NULL: an account; set: the comments of someone who left
  last_seen_at timestamp(0),
  online_seconds bigint NOT NULL DEFAULT 0,
  created_at timestamp(0) NOT NULL DEFAULT utc_now()
);

CREATE TABLE auth_session (
  id_hash varchar(64) PRIMARY KEY,                   -- SHA-256 of the cookie token, hex
  user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  csrf_token varchar(43) NOT NULL,
  created_at timestamp(0) NOT NULL DEFAULT utc_now(),
  expires_at timestamp(0) NOT NULL,
  last_seen_at timestamp(0) NOT NULL DEFAULT utc_now(),
  ip varchar(45) NOT NULL,
  user_agent varchar(255) NOT NULL DEFAULT ''
);
CREATE INDEX auth_session_user ON auth_session (user_id);
CREATE INDEX auth_session_expires ON auth_session (expires_at);

CREATE TABLE email_token (
  token_hash varchar(64) PRIMARY KEY,                -- SHA-256 of the token in the mailed link, hex
  user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  purpose text NOT NULL CHECK (purpose IN ('verify', 'reset')),
  expires_at timestamp(0) NOT NULL,
  used_at timestamp(0),
  created_at timestamp(0) NOT NULL DEFAULT utc_now()
);
CREATE INDEX email_token_user ON email_token (user_id, purpose);

CREATE TABLE user_identity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  provider text NOT NULL CHECK (provider IN ('github', 'google')),
  provider_user_id varchar(64) NOT NULL,             -- GitHub's numeric id, Google's sub
  login varchar(254) NOT NULL,                       -- what the account page shows: the GitHub login, the Google address
  avatar_url varchar(512),                           -- GitHub's avatar_url, Google's picture
  created_at timestamp(0) NOT NULL DEFAULT utc_now(),
