CREATE TABLE note (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  original_lang text NOT NULL CHECK (original_lang IN ('zh', 'en')),
  mood varchar(20) NOT NULL DEFAULT '',
  weather varchar(20) NOT NULL DEFAULT '',
  cover varchar(255) NOT NULL DEFAULT '',
  comments_enabled boolean NOT NULL DEFAULT true,
  word_count bigint NOT NULL DEFAULT 0,
  created_at timestamp(0) NOT NULL DEFAULT utc_now(),
  updated_at timestamp(0) NOT NULL DEFAULT utc_now(),
  published_at timestamp(0),
  mailed_at timestamp(0)
);
CREATE INDEX note_published ON note (status, published_at, id);

CREATE TABLE note_translation (
  note_id bigint NOT NULL REFERENCES note (id) ON DELETE CASCADE,
  lang text NOT NULL CHECK (lang IN ('zh', 'en')),
  title varchar(200) NOT NULL,
  body_md text NOT NULL,
  PRIMARY KEY (note_id, lang)
);

CREATE TABLE thinking (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status text NOT NULL DEFAULT 'published' CHECK (status IN ('draft', 'published')),
  original_lang text NOT NULL CHECK (original_lang IN ('zh', 'en')),
  comments_enabled boolean NOT NULL DEFAULT true,
  created_at timestamp(0) NOT NULL DEFAULT utc_now(),
  updated_at timestamp(0) NOT NULL DEFAULT utc_now(),
  published_at timestamp(0)
);
CREATE INDEX thinking_published ON thinking (status, published_at, id);

CREATE TABLE thinking_translation (
  thinking_id bigint NOT NULL REFERENCES thinking (id) ON DELETE CASCADE,
  lang text NOT NULL CHECK (lang IN ('zh', 'en')),
  body_md text NOT NULL,
  PRIMARY KEY (thinking_id, lang)
);

ALTER TABLE comment
  ADD COLUMN note_id bigint REFERENCES note (id) ON DELETE CASCADE,
  ADD COLUMN thinking_id bigint REFERENCES thinking (id) ON DELETE CASCADE,
  DROP CONSTRAINT comment_target_kind_check,
  ADD CONSTRAINT comment_target_kind_check CHECK (target_kind IN ('post', 'note', 'thinking', 'guestbook'));
CREATE INDEX comment_note ON comment (note_id);
CREATE INDEX comment_thinking ON comment (thinking_id);

ALTER TABLE reaction
